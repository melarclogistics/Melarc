/** An item is as tall as a dense control (36px). `destructive` is the danger text on the soft danger fill: a menu item is never a filled danger button. */
function DropdownMenuItem({
  className,
  inset,
  variant = 'default',
  ...props
}: React.ComponentProps<typeof DropdownMenuPrimitive.Item> & {
  inset?: boolean;
  variant?: 'default' | 'destructive';
}) {
  return (
    <DropdownMenuPrimitive.Item
      data-slot="dropdown-menu-item"
      data-inset={inset}
      data-variant={variant}
      className={cn(
        "relative flex min-h-(--control-height-sm) cursor-default items-center gap-2 rounded-md px-3 py-1 text-sm select-none focus:bg-accent focus:text-accent-foreground active:bg-(color:--button-pressed-background) data-disabled:pointer-events-none data-disabled:text-(color:--color-text-disabled) data-inset:pl-9 data-[variant=destructive]:text-destructive data-[variant=destructive]:focus:bg-(color:--color-status-danger-background) data-[variant=destructive]:focus:text-destructive [&_svg]:pointer-events-none [&_svg]:shrink-0 [&_svg:not([class*='size-'])]:size-4",
        className,
      )}
      {...props}
    />
  );
}

