/*
 * A menu floats: the raised surface, the default border, the one soft shadow, `motion.normal` in and out (design/DESIGN_SYSTEM.md section 9). Its
 * padding is the 4px that holds the frame's focus ring (2px, and 2px of offset) inside the list, so the ring on an item is never cut.
 *
 * `container` is not in the registry's source (design/DESIGN_SYSTEM.md section 29.6), as the popover's is not: the element the menu is drawn into, the body unless one is
 * given. A modal `<dialog>` is in the top layer and the page behind it is inert, so a menu opened from inside one is drawn into the dialog, or it would open under it.
 */
function DropdownMenuContent({
  className,
  sideOffset = 4,
  container,
  ...props
}: React.ComponentProps<typeof DropdownMenuPrimitive.Content> & {
  container?: HTMLElement | null;
}) {
  return (
    <DropdownMenuPrimitive.Portal container={container}>
      <DropdownMenuPrimitive.Content
        data-slot="dropdown-menu-content"
        sideOffset={sideOffset}
        className={cn(
          'z-50 max-h-(--radix-dropdown-menu-content-available-height) min-w-32 origin-(--radix-dropdown-menu-content-transform-origin) overflow-x-hidden overflow-y-auto rounded-lg border border-border bg-popover p-1 text-popover-foreground shadow-md duration-(--motion-normal) ease-(--motion-ease-enter) data-[side=bottom]:slide-in-from-top-2 data-[side=left]:slide-in-from-right-2 data-[side=right]:slide-in-from-left-2 data-[side=top]:slide-in-from-bottom-2 data-[state=closed]:ease-(--motion-ease-exit) data-[state=closed]:animate-out data-[state=closed]:fade-out-0 data-[state=closed]:zoom-out-95 data-[state=open]:animate-in data-[state=open]:fade-in-0 data-[state=open]:zoom-in-95',
          className,
        )}
        {...props}
      />
    </DropdownMenuPrimitive.Portal>
  );
}

