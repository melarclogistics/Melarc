/** Whether an entry of `SHADCN_ACCOUNTED` covers a package: by its name, or, for `@scope/*`, by the scope. */
export function covers(entry: string, name: string): boolean {
  return entry.endsWith('/*') ? name.startsWith(entry.slice(0, -1)) : entry === name;
}

/** The entry of `SHADCN_ACCOUNTED` that covers a package, if one does. */
export function entryFor(name: string): string | NoLicence | undefined {
  const key = Object.keys(SHADCN_ACCOUNTED).find((entry) => covers(entry, name));
  return key === undefined ? undefined : SHADCN_ACCOUNTED[key];
}

const nameOf = (key: string): string => /^(@?[^@]+)@/.exec(key)?.[1] ?? key;

/**
 * The folder of a package as another package sees it. pnpm links the dependencies of a package beside it, in the node_modules folder that holds
 * it, so the walk goes up from the dependent; no "exports" field is read, which keeps a package that has only CSS (tw-animate-css) findable.
 */
function directoryOf(from: string, name: string): string {
  for (let directory = from; ; directory = dirname(directory)) {
    const candidate = join(directory, 'node_modules', name);
    if (existsSync(join(candidate, 'package.json'))) return realpathSync(candidate);
    if (dirname(directory) === directory)
      throw new Error(`${name} is not installed above ${from}.`);
  }
}

/**
 * Every package that `roots` (dependencies of the portal) bring, by name, with the folder of each version installed. The tree is read from the
 * lockfile and the folders from the install, so the two cannot disagree without the test saying so. React and React DOM are the application's own.
 */
export function treeOf(appRoot: string, roots: readonly string[]): Map<string, string[]> {
  const lock = parse(readFileSync(LOCKFILE, 'utf8')) as Lockfile;
  const importer = lock.importers['apps/ops-web'];
  const direct = { ...importer?.dependencies, ...importer?.devDependencies };
  const queue: { key: string; directory: string }[] = [];
  for (const root of roots) {
    const version = direct[root]?.version;
    if (version === undefined) throw new Error(`${root} is not a dependency of the portal.`);
    queue.push({ key: `${root}@${version}`, directory: directoryOf(appRoot, root) });
  }
  const seen = new Set(queue.map((item) => item.key));
  const found = new Map<string, Set<string>>();
  for (let item = queue.shift(); item !== undefined; item = queue.shift()) {
    const name = nameOf(item.key);
    found.set(name, (found.get(name) ?? new Set<string>()).add(item.directory));
    const snapshot = lock.snapshots[item.key];
    const children = { ...snapshot?.dependencies, ...snapshot?.optionalDependencies };
    for (const [childName, version] of Object.entries(children)) {
      if (childName === 'react' || childName === 'react-dom') continue;
      const childKey = `${childName}@${version}`;
      if (seen.has(childKey)) continue;
      seen.add(childKey);
      queue.push({ key: childKey, directory: directoryOf(item.directory, childName) });
    }
  }
  return new Map([...found].map(([name, folders]) => [name, [...folders]]));
}

/** The folder of a package of the portal itself (a dependency it names). */
export function ownDirectory(appRoot: string, name: string): string {
  return directoryOf(appRoot, name);
}

/** The licence file of a package, as the package names it, or nothing when it holds none. */
export function licenceFileOf(directory: string): string | undefined {
  return readdirSync(directory).find((entry) => /^licen[cs]e(?:\.md|\.txt)?$/i.test(entry));
}

/** The text of a package's licence file. */
export function licenceTextOf(directory: string): string {
  const file = licenceFileOf(directory);
  if (file === undefined) throw new Error(`${directory} holds no licence file.`);
  return readFileSync(join(directory, file), 'utf8');
}
