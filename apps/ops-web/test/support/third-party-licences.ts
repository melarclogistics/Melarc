interface Snapshot {
  readonly dependencies?: Readonly<Record<string, string>>;
  readonly optionalDependencies?: Readonly<Record<string, string>>;
}

interface Importer {
  readonly dependencies?: Readonly<Record<string, { readonly version: string }>>;
  readonly devDependencies?: Readonly<Record<string, { readonly version: string }>>;
}

interface Lockfile {
  readonly importers: Readonly<Record<string, Importer | undefined>>;
  readonly snapshots: Readonly<Record<string, Snapshot | undefined>>;
}

