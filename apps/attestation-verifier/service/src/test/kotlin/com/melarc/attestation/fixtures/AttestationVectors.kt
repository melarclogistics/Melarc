package com.melarc.attestation.fixtures

import com.google.gson.GsonBuilder
import com.google.gson.JsonArray
import com.google.gson.JsonObject
import java.nio.file.Files
import java.nio.file.Path
import java.util.Base64

/**
 * The attestation chains the API's tests send to the **real** service (S0.57, `rider-device-enrolment-attested.db.test.ts`), published as one
 * file the Node tests read: the chains of [AttestationFixtures], made by [DeterministicPki] from nothing the service under test contains, so
 * that the API is held to a service that was qualified on evidence it did not write. Each case carries the chain, the 32 bytes the grant
 * would have issued with it, the key to submit, and the verdict the policy must give; the file carries the service settings the chains
 * assume (the Rider package, the approved signing digests, the accepted roots, the serials on the revocation list).
 *
 * It is a selection, one chain for each class of evidence the acceptance criteria name (`AC-SLICE-000-60` to `-66`, `-70`), and not the whole
 * matrix of [PolicyVerifierTest]: those 85 chains are the JVM's own. The file is regenerated by `./gradlew :service:attestationVectors`
 * and held to a fresh run by [AttestationVectorsTest], so a file no generator made, or a fixture that changed without it, fails the build.
 */
object AttestationVectors {
  /** The cases, by the name of the fixture, in the order the file lists them. */
  val SELECTION: List<String> =
    listOf(
      // AC-60: a hardware-attested key is enrolled (TrustedEnvironment; StrongBox accepted and not required; a remotely provisioned chain).
      "valid_trusted_environment",
      "valid_strongbox",
      "valid_remotely_provisioned",
      "valid_second_accepted_root",
      // AC-70: the signing certificate can be rotated (each approved digest alone, and both).
      "valid_rotated_signer",
      "valid_both_approved_signers",
      // AC-61: a handset that cannot hold a hardware-backed key.
      "software_attestation",
      // AC-62: evidence for the wrong application.
      "package_other",
      "signer_unapproved",
      // AC-63: an untrusted chain, a revoked certificate, an appended extension, a malformed one.
      "unknown_root",
      "intermediate_revoked",
      "attestation_certificate_revoked",
      "leaf_revoked",
      "signature_of_leaf_broken",
      "chain_extended_with_fake_leaf",
      "leaf_extension_duplicated",
      "extension_nested_to_the_limit_of_a_certificate",
      // AC-64: evidence for a different challenge.
      "challenge_other",
      // AC-65: an unlocked or an unverified device.
      "device_unlocked",
      "boot_unverified",
      // The key properties (step 9), and AC-66: a key that is not the attested key.
      "key_is_rsa",
      "key_other_than_the_attested",
    )

  private val encoder: Base64.Encoder = Base64.getEncoder()
  private val urlEncoder: Base64.Encoder = Base64.getUrlEncoder().withoutPadding()

  private fun strings(values: Iterable<String>): JsonArray = JsonArray().also { array -> values.forEach { array.add(it) } }

  private fun expected(case: FixtureCase): JsonObject =
    JsonObject().also { json ->
      when (val result = case.expected) {
        is Expected.Verified -> {
          json.addProperty("verdict", "VERIFIED")
          json.addProperty("security_level", result.securityLevel)
          json.add("signer_digests", strings(result.signers.map { it.hex() }))
        }
        is Expected.IntegrityFailed -> {
          json.addProperty("verdict", "DEVICE_INTEGRITY_FAILED")
          json.addProperty("cause", result.cause.name)
        }
        Expected.SecurityUnsupported -> json.addProperty("verdict", "DEVICE_SECURITY_UNSUPPORTED")
      }
    }

  private fun caseJson(case: FixtureCase): JsonObject =
    JsonObject().also { json ->
      json.addProperty("name", case.name)
      json.addProperty("description", case.description)
      json.add("certificate_chain", strings(case.chain.map { encoder.encodeToString(it) }))
      // The 32 bytes the grant issues, as the QR carries them; the API keeps only their SHA-256.
      json.addProperty("challenge", urlEncoder.encodeToString(case.issuedChallenge))
      json.addProperty("device_public_key", encoder.encodeToString(case.devicePublicKey))
      json.add("expected", expected(case))
    }

  /** The file: pretty printed, one trailing newline, and nothing in it that is a private key. */
  fun document(): String {
    val selected = SELECTION.map { AttestationFixtures.named(it) }
    val service =
      JsonObject().also { json ->
        json.addProperty("package_name", FixtureWorld.PACKAGE)
        json.add("signing_digests", strings(listOf(FixtureWorld.SIGNER_1.hex(), FixtureWorld.SIGNER_2.hex())))
        json.add("accepted_roots", strings(FixtureWorld.ACCEPTED_ROOTS.map { FixtureWorld.pem(it.certificate) }))
        // Every list holds the decoy; the serials of a case are its own (derived from its label), so the union of what the selection revokes
        // revokes no other case's certificate.
        json.add(
          "revoked_serials",
          strings((selected.flatMap { it.revokedSerials } + FixtureWorld.DECOY_SERIAL).toSortedSet()),
        )
      }
    val root =
      JsonObject().also { json ->
        json.addProperty("version", 1)
        json.addProperty(
          "note",
          "Made by apps/attestation-verifier (AttestationVectors.kt) from its deterministic fixtures. Regenerate with `./gradlew :service:attestationVectors`; never edit by hand.",
        )
        json.add("service", service)
        json.add("cases", JsonArray().also { array -> selected.forEach { array.add(caseJson(it)) } })
      }
    return GsonBuilder().setPrettyPrinting().disableHtmlEscaping().create().toJson(root) + "\n"
  }
}

/** `./gradlew :service:attestationVectors`: writes the file the API's tests read. */
fun main(args: Array<String>) {
  require(args.size == 1) { "usage: GenerateAttestationVectors <path of attestation-chains.v1.json>" }
  Files.writeString(Path.of(args[0]), AttestationVectors.document())
}
