import {
  existsSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  readdirSync,
  rmSync,
  statSync,
  symlinkSync,
  writeFileSync,
} from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';

import { afterEach, beforeEach, describe, expect, it } from 'vitest';

import {
  LEAF_EXTENSIONS,
  TestCaRefusedError,
  mintTestCertificates,
  opensslRunner,
  type OpensslRun,
} from './test-ca.ts';
import { TLS_FILES, type TlsMaterialResult } from './tls-material.ts';

/**
 * The generator of the test CA (S0.23), run against a **fake `openssl`** that writes placeholder text where the real one writes a
 * key or a certificate. **No key is generated by any test here.** What these prove is what the tool decides itself: where it will
 * write, what it asks `openssl` to make, in what order, that the CA's key is gone when it is done, that a failure leaves nothing,
 * and that it prints nothing secret. That `openssl` accepts the arguments and the result passes the policy is proved by the run on a
 * clean machine or in CI (`e2e/README.md`), and is reported blocked until then.
 */
const KEY = 'PLACEHOLDER-PRIVATE-KEY-TEXT';
let base = '';
let checkout = '';

beforeEach(() => {
  base = mkdtempSync(join(tmpdir(), 'melarc-test-ca-'));
  checkout = join(base, 'checkout');
});
afterEach(() => {
  rmSync(base, { recursive: true, force: true });
});

interface Call {
  readonly args: readonly string[];
  readonly cwd: string;
  /** The extension file the leaf was signed with, as it was when `openssl` was called. */
  readonly extensions?: string;
}

/**
 * An `openssl` that writes a placeholder at every `-out` and records the call. `failOn` is the index of the call that fails.
 * `during` runs at the start of a call with its index and working directory, to leave something where the real tool might.
 *
 * It does what the real `x509 -CAcreateserial` does with the serial file: the one `-CAserial` names, or else the CA certificate's
 * name with `.srl` (which, for a certificate given as `../ca.pem`, is in the directory the result is kept in).
 */
function fakeOpenssl(
  failOn?: number,
  during?: (index: number, cwd: string) => void,
): { run: OpensslRun; calls: Call[] } {
  const calls: Call[] = [];
  const run: OpensslRun = (args, cwd) => {
    const extension = args.includes('-extfile')
      ? readFileSync(join(cwd, 'leaf.ext'), 'utf8')
      : undefined;
    calls.push({ args, cwd, ...(extension === undefined ? {} : { extensions: extension }) });
    during?.(calls.length - 1, cwd);
    if (failOn === calls.length - 1) throw new Error('openssl failed');
    const out = args[args.indexOf('-out') + 1];
    if (out !== undefined)
      writeFileSync(resolve(cwd, out), args[0] === 'genpkey' ? KEY : 'PLACEHOLDER-CERT');
    if (args.includes('-CAcreateserial')) {
      const named = args.includes('-CAserial') ? args[args.indexOf('-CAserial') + 1] : undefined;
      const certificate = args[args.indexOf('-CA') + 1] ?? '';
      writeFileSync(resolve(cwd, named ?? certificate.replace(/\.[^./\\]*$/, '.srl')), '01');
    }
  };
  return { run, calls };
}

const accepted: (directory: string) => TlsMaterialResult = (directory) => ({
  ok: true,
  material: {
    directory,
    caPath: join(directory, TLS_FILES.ca),
    leafPath: join(directory, TLS_FILES.leaf),
    leafKeyPath: join(directory, TLS_FILES.leafKey),
    caFingerprint256: 'AA:AA',
    leafFingerprint256: 'BB:BB',
    notes: [],
  },
});

const target = (): string => join(base, 'tls');

describe('where it will write', () => {
  // Break caught: key material generated into the checkout, where `git add .` or a source archive could take it.
  it('refuses a directory inside the checkout, and runs nothing', () => {
    const { run, calls } = fakeOpenssl();

    expect(() =>
      mintTestCertificates({
        directory: join(checkout, 'tls'),
        checkoutRoot: checkout,
        run,
        verify: accepted,
      }),
    ).toThrow(TestCaRefusedError);
    expect(calls).toEqual([]);
    expect(existsSync(join(checkout, 'tls'))).toBe(false);
  });

  // Break caught: an existing key overwritten, or a directory that holds other things filled with key material.
  it('refuses a directory that is not empty, and leaves it as it was', () => {
    const { run, calls } = fakeOpenssl();
    const directory = mkdtempSync(join(base, 'full-'));
    writeFileSync(join(directory, 'something.txt'), 'kept');

    expect(() =>
      mintTestCertificates({ directory, checkoutRoot: checkout, run, verify: accepted }),
    ).toThrow(/not empty/);
    expect(calls).toEqual([]);
    expect(readFileSync(join(directory, 'something.txt'), 'utf8')).toBe('kept');
  });

  // Break caught: a directory that leads into the checkout through a link taken to be outside it because its written path is.
  it('refuses a directory that leads into the checkout through a link, and runs nothing', () => {
    mkdirSync(checkout, { recursive: true });
    symlinkSync(checkout, join(base, 'alias'), 'junction');
    const { run, calls } = fakeOpenssl();

    expect(() =>
      mintTestCertificates({
        directory: join(base, 'alias', 'tls'),
        checkoutRoot: checkout,
        run,
        verify: accepted,
      }),
    ).toThrow(/inside the repository checkout/);
    expect(calls).toEqual([]);
    expect(readdirSync(checkout)).toEqual([]);
  });

  it.each([0, -1, 1.5, 32, Number.NaN])('refuses %s days', (days) => {
    const { run, calls } = fakeOpenssl();

    expect(() =>
      mintTestCertificates({
        directory: target(),
        checkoutRoot: checkout,
        days,
        run,
        verify: accepted,
      }),
    ).toThrow(/whole number of days from 1 to 31/);
    expect(calls).toEqual([]);
  });

  it('refuses a directory that is not an absolute path', () => {
    const { run } = fakeOpenssl();

    expect(() =>
      mintTestCertificates({ directory: 'tls', checkoutRoot: checkout, run, verify: accepted }),
    ).toThrow(/not an absolute path/);
  });

  it('accepts an empty directory that already exists, and leaves it in place', () => {
    const directory = mkdtempSync(join(base, 'empty-'));
    const { run } = fakeOpenssl();

    mintTestCertificates({ directory, checkoutRoot: checkout, run, verify: accepted });

    expect(readdirSync(directory).toSorted()).toEqual(
      [TLS_FILES.ca, TLS_FILES.leaf, TLS_FILES.leafKey].toSorted(),
    );
  });
});

describe('what it asks openssl to make', () => {
  // Break caught: a CA that can sign for anything, a leaf that is itself a CA, or one that does not name the loopback.
  it('makes a P-256 CA that is constrained to the loopback, then a leaf it signs, in that order', () => {
    const { run, calls } = fakeOpenssl();

    mintTestCertificates({ directory: target(), checkoutRoot: checkout, run, verify: accepted });

    expect(calls.map((call) => call.args.slice(0, 2).join(' '))).toEqual([
      'genpkey -algorithm',
      'req -new',
      'genpkey -algorithm',
      'req -new',
      'x509 -req',
    ]);
    const [caKey, caCertificate, leafKey, leafRequest, leafSigning] = calls;
    expect(caKey?.args).toEqual(expect.arrayContaining(['EC', 'ec_paramgen_curve:P-256']));
    expect(leafKey?.args).toEqual(expect.arrayContaining(['EC', 'ec_paramgen_curve:P-256']));
    const extensions = caCertificate?.args.filter((_, at, all) => all[at - 1] === '-addext') ?? [];
    expect(extensions).toEqual([
      'basicConstraints=critical,CA:TRUE,pathlen:0',
      'keyUsage=critical,keyCertSign,cRLSign',
      'nameConstraints=critical,permitted;DNS:localhost,permitted;IP:127.0.0.1/255.255.255.255',
    ]);
    expect(caCertificate?.args).toEqual(expect.arrayContaining(['-x509', '-sha256']));
    expect(leafRequest?.args).toEqual(expect.arrayContaining(['-subj', '/CN=localhost']));
    expect(leafSigning?.extensions).toBe(LEAF_EXTENSIONS);
    expect(LEAF_EXTENSIONS).toContain('CA:FALSE');
    expect(LEAF_EXTENSIONS).toContain('serverAuth');
    expect(LEAF_EXTENSIONS).toContain('subjectAltName = DNS:localhost, IP:127.0.0.1');
  });

  // Break caught: certificates that last for years because the default of a tool was taken.
  it('gives both certificates the days asked for, seven unless told otherwise', () => {
    const seven = fakeOpenssl();
    const three = fakeOpenssl();

    mintTestCertificates({
      directory: target(),
      checkoutRoot: checkout,
      run: seven.run,
      verify: accepted,
    });
    mintTestCertificates({
      directory: join(base, 'three'),
      checkoutRoot: checkout,
      days: 3,
      run: three.run,
      verify: accepted,
    });

    const daysOf = (calls: Call[]): string[] =>
      calls.flatMap((call) =>
        call.args.includes('-days') ? [call.args[call.args.indexOf('-days') + 1] ?? ''] : [],
      );
    expect(daysOf(seven.calls)).toEqual(['7', '7']);
    expect(daysOf(three.calls)).toEqual(['3', '3']);
  });

  it('signs the leaf with the CA certificate and the CA key, and writes where the policy looks', () => {
    const { run, calls } = fakeOpenssl();

    mintTestCertificates({ directory: target(), checkoutRoot: checkout, run, verify: accepted });

    const signing = calls[4]?.args ?? [];
    expect(signing[signing.indexOf('-CA') + 1]).toBe(join('..', TLS_FILES.ca));
    expect(signing[signing.indexOf('-CAkey') + 1]).toBe('ca-key.pem');
    expect(signing[signing.indexOf('-out') + 1]).toBe(join('..', TLS_FILES.leaf));
  });

  // Break caught: the serial file left to its default, which is next to the CA certificate: in the directory the result is kept in.
  it('keeps the serial file of the CA in the work directory, where it is removed with the rest', () => {
    const { run, calls } = fakeOpenssl();

    mintTestCertificates({ directory: target(), checkoutRoot: checkout, run, verify: accepted });

    const signing = calls[4]?.args ?? [];
    expect(signing).toContain('-CAcreateserial');
    const serial = signing[signing.indexOf('-CAserial') + 1] ?? '';
    expect(serial).toMatch(/^[^\\/]+\.srl$/);
  });
});

describe('what is left', () => {
  // Break caught: the CA's private key surviving the run, so that anything that ever trusts the CA could be forged for.
  it('leaves the two certificates and the leaf key, and no CA key, no request and no work directory', () => {
    const { run } = fakeOpenssl();

    mintTestCertificates({ directory: target(), checkoutRoot: checkout, run, verify: accepted });

    expect(readdirSync(target()).toSorted()).toEqual(
      [TLS_FILES.ca, TLS_FILES.leaf, TLS_FILES.leafKey].toSorted(),
    );
    expect(readFileSync(join(target(), TLS_FILES.leafKey), 'utf8')).toBe(KEY);
  });

  it.skipIf(process.platform === 'win32')('makes the leaf key readable by its owner alone', () => {
    const { run } = fakeOpenssl();

    mintTestCertificates({ directory: target(), checkoutRoot: checkout, run, verify: accepted });

    expect(statSync(join(target(), TLS_FILES.leafKey)).mode & 0o777).toBe(0o600);
    expect(statSync(target()).mode & 0o777).toBe(0o700);
  });

  // Break caught: the result carrying key bytes, which a log line or a report would then print.
  it('returns paths and fingerprints and nothing of a key', () => {
    const { run } = fakeOpenssl();

    const result = mintTestCertificates({
      directory: target(),
      checkoutRoot: checkout,
      run,
      verify: accepted,
    });

    expect(JSON.stringify(result)).not.toContain(KEY);
    expect(result).toMatchObject({ caFingerprint256: 'AA:AA', leafFingerprint256: 'BB:BB' });
  });
});

describe('a failure', () => {
  // Break caught: a failed run leaving half a CA behind: a key with no certificate, or a certificate with no way to tell.
  it.each([0, 1, 2, 3, 4])(
    'at openssl call %i leaves nothing, the CA key included, and reports it',
    (failing) => {
      const { run } = fakeOpenssl(failing);

      expect(() =>
        mintTestCertificates({
          directory: target(),
          checkoutRoot: checkout,
          run,
          verify: accepted,
        }),
      ).toThrow('openssl failed');

      expect(existsSync(target())).toBe(false);
    },
  );

  it('empties an existing directory it was given, and leaves the directory', () => {
    const directory = mkdtempSync(join(base, 'given-'));
    const { run } = fakeOpenssl(4);

    expect(() =>
      mintTestCertificates({ directory, checkoutRoot: checkout, run, verify: accepted }),
    ).toThrow('openssl failed');

    expect(readdirSync(directory)).toEqual([]);
  });

  // Break caught: a failure that removes the files it knows of and leaves the rest of what the run put in the directory.
  it('empties the directory it was given of whatever the run left in it, not only of the three files', () => {
    const directory = mkdtempSync(join(base, 'given-'));
    const { run } = fakeOpenssl(4, (index, cwd) => {
      if (index === 3) writeFileSync(resolve(cwd, '..', 'left-behind.txt'), 'x');
    });

    expect(() =>
      mintTestCertificates({ directory, checkoutRoot: checkout, run, verify: accepted }),
    ).toThrow('openssl failed');

    expect(readdirSync(directory)).toEqual([]);
  });

  // Break caught: the folders a run made left behind (a path of several new folders), or a folder that was there removed with them.
  it('removes every folder it made, and none that was already there', () => {
    const existing = mkdtempSync(join(base, 'existing-'));
    writeFileSync(join(existing, 'kept.txt'), 'kept');
    const { run } = fakeOpenssl(3);

    expect(() =>
      mintTestCertificates({
        directory: join(existing, 'new', 'deeper', 'tls'),
        checkoutRoot: checkout,
        run,
        verify: accepted,
      }),
    ).toThrow('openssl failed');

    expect(readdirSync(existing)).toEqual(['kept.txt']);
  });

  // Break caught: a directory that holds more than the three files handed over because the three are there and acceptable.
  it('refuses a result that holds anything but the three files, and removes it all', () => {
    const { run } = fakeOpenssl(undefined, (index, cwd) => {
      if (index === 2) writeFileSync(resolve(cwd, '..', 'ca.srl'), '01');
    });

    expect(() =>
      mintTestCertificates({ directory: target(), checkoutRoot: checkout, run, verify: accepted }),
    ).toThrow(/more than the three files that were asked for: ca\.srl/);

    expect(existsSync(target())).toBe(false);
  });

  it('empties a directory it was given when the result holds anything but the three files', () => {
    const directory = mkdtempSync(join(base, 'given-'));
    const { run } = fakeOpenssl(undefined, (index, cwd) => {
      if (index === 0) writeFileSync(resolve(cwd, '..', 'notes.txt'), 'x');
    });

    expect(() =>
      mintTestCertificates({ directory, checkoutRoot: checkout, run, verify: accepted }),
    ).toThrow(/more than the three files/);

    expect(readdirSync(directory)).toEqual([]);
  });

  // Break caught: material the policy does not accept being handed over because openssl was content with it.
  it('removes what it made when the policy does not accept it, and says why', () => {
    const { run } = fakeOpenssl();
    const refuse = (): TlsMaterialResult => ({
      ok: false,
      problems: ['the leaf certificate was not signed by this CA'],
    });

    expect(() =>
      mintTestCertificates({ directory: target(), checkoutRoot: checkout, run, verify: refuse }),
    ).toThrow(/was not signed by this CA/);

    expect(existsSync(target())).toBe(false);
  });
});

describe('opensslRunner', () => {
  const node = (script: string): [string, string[]] => [process.execPath, ['-e', script]];

  it('runs a command to success without keeping its output', () => {
    const [command, args] = node('process.stdout.write("secret-looking output")');

    expect(() => {
      opensslRunner(command)(args, base);
    }).not.toThrow();
  });

  // Break caught: a failed step read as success, or a failure that does not say which step it was.
  it('fails with the step and the exit status, and the end of what the tool said', () => {
    const [command, args] = node(
      'process.stderr.write("line one\\nline two\\nline three\\nline four"); process.exit(3)',
    );

    expect(() => {
      opensslRunner(command)(args, base);
    }).toThrow(/"-e" failed \(exit 3\): line two \| line three \| line four/);
  });

  it('fails clearly when the command cannot be started', () => {
    expect(() => {
      opensslRunner(join(base, 'no-such-openssl'))(['version'], base);
    }).toThrow(/could not be run for "version"/);
  });
});
