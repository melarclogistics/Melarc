describe('where the material may be kept, wherever a path leads', () => {
  const INSIDE =
    'the TLS directory is inside the repository checkout: test key material is kept outside it';
  let base = '';
  let checkout = '';
  let elsewhere = '';

  beforeEach(() => {
    base = mkdtempSync(join(tmpdir(), 'melarc-tls-aliases-'));
    checkout = join(base, 'checkout');
    elsewhere = join(base, 'elsewhere');
    mkdirSync(join(checkout, 'tmp'), { recursive: true });
    mkdirSync(elsewhere);
  });
  afterEach(() => {
    rmSync(base, { recursive: true, force: true });
  });

  // Break caught: a link or junction outside the checkout that leads into it taken to be outside because its written path is: key
  // material would be written into the checkout, where `git add .` or a source archive takes it.
  it('refuses a directory reached through a link into the checkout, whether it exists yet or not', () => {
    const alias = join(base, 'alias');
    symlinkSync(checkout, alias, 'junction');

    for (const reached of [
      alias,
      join(alias, 'tmp'),
      join(alias, 'tmp', 'tls'),
      join(alias, 'new', 'deeper', 'tls'),
    ]) {
      expect(directoryProblems(reached, checkout), reached).toEqual([INSIDE]);
    }
  });

  // Break caught: the checkout compared as written while the directory is resolved, or the reverse: the same place, two spellings.
  it('refuses a directory in the checkout when the checkout is the one named through a link', () => {
    const alias = join(base, 'alias');
    symlinkSync(checkout, alias, 'junction');

    expect(directoryProblems(join(checkout, 'tmp', 'tls'), alias)).toEqual([INSIDE]);
  });

  it('accepts a directory reached through a link that leads somewhere else', () => {
    const away = join(base, 'away');
    symlinkSync(elsewhere, away, 'junction');

    expect(directoryProblems(join(away, 'tls'), checkout)).toEqual([]);
    expect(directoryProblems(join(away, 'new', 'tls'), checkout)).toEqual([]);
  });

  // Break caught: the extended-length spelling of a Windows path (`\\?\C:\...`), which has no relative path to the same checkout
  // spelled the usual way, taken to be on another drive.
  it.skipIf(process.platform !== 'win32')(
    'refuses the extended-length spelling of a directory in the checkout',
    () => {
      expect(directoryProblems(`\\\\?\\${join(checkout, 'tmp', 'tls')}`, checkout)).toEqual([
        INSIDE,
      ]);
      expect(directoryProblems(`\\\\?\\${join(elsewhere, 'tls')}`, checkout)).toEqual([]);
    },
  );

  it('resolves what exists and keeps what does not', () => {
    const alias = join(base, 'alias');
    symlinkSync(checkout, alias, 'junction');

    expect(resolvedPath(join(alias, 'tmp', 'new', 'tls'))).toBe(
      join(resolvedPath(checkout), 'tmp', 'new', 'tls'),
    );
  });

  // Break caught: the path as written left out because the resolved one is the truth. It counts too: a link inside the checkout that
  // leads out of it does not make a folder written under the checkout acceptable (somebody has made a mistake, and what is
  // physically elsewhere is not what the path says).
  it('refuses a directory written inside the checkout even where a link there leads out of it', () => {
    symlinkSync(elsewhere, join(checkout, 'outbound'), 'junction');

    expect(directoryProblems(join(checkout, 'outbound', 'tls'), checkout)).toEqual([INSIDE]);
  });

  // Break caught: the resolved paths left out because the identities seem to say it all: a file system that gives no identity (a share
  // that reports 0 for every file) then lets a link into the checkout through.
  it('refuses a directory reached through a link even where the file system gives no identity', () => {
    const alias = join(base, 'alias');
    symlinkSync(checkout, alias, 'junction');
    const none = (): undefined => undefined;

    expect(directoryProblems(join(alias, 'tmp', 'tls'), checkout, none)).toEqual([INSIDE]);
    expect(directoryProblems(join(elsewhere, 'tls'), checkout, none)).toEqual([]);
  });

  // Break caught: the identity of a folder compared by its text or taken from a missing one, so that the same folder under another
  // name (a share, a bind mount) is missed, or that everything looks like it.
  it('knows a folder above a directory by its identity, and only that one', () => {
    expect(isSameFolderAbove(checkout, join(checkout, 'tmp', 'tls'))).toBe(true);
    expect(isSameFolderAbove(checkout, join(checkout, 'tmp'))).toBe(true);
    expect(isSameFolderAbove(checkout, checkout)).toBe(true);
    expect(isSameFolderAbove(checkout, join(elsewhere, 'tls'))).toBe(false);
    expect(isSameFolderAbove(checkout, base)).toBe(false);
    expect(isSameFolderAbove(join(base, 'missing'), join(elsewhere, 'tls'))).toBe(false);
  });

  // Break caught: a folder that is the checkout under another name (a bind mount, a share of the local disk), which neither the
  // written path nor the resolved one gives away, accepted. The file system is simulated: one name is made the checkout's twin.
  it('refuses a directory under a folder that is the checkout by identity, whatever it is called', () => {
    const twin = join(elsewhere, 'mounted');
    mkdirSync(twin);
    const bound = (path: string): string | undefined => {
      const real = resolvedPath(path);
      if (real === resolvedPath(checkout) || real === resolvedPath(twin)) return 'one-folder';
      return real;
    };

    expect(directoryProblems(join(twin, 'tls'), checkout)).toEqual([]);
    expect(directoryProblems(join(twin, 'tls'), checkout, bound)).toEqual([INSIDE]);
    expect(directoryProblems(join(elsewhere, 'other', 'tls'), checkout, bound)).toEqual([]);
  });
});

describe('the files of a directory', () => {
  let directory = '';
  const checkout = resolve(tmpdir(), 'melarc-never-the-checkout');

  beforeEach(() => {
    directory = mkdtempSync(join(tmpdir(), 'melarc-tls-policy-'));
  });
  afterEach(() => {
    rmSync(directory, { recursive: true, force: true });
  });

  const write = (file: string, content: string): void => {
    writeFileSync(join(directory, file), content);
  };

  // Break caught: a run that starts HTTPS with files that are not there and fails in the middle of the browser's handshake.
  it('names every file that is missing', () => {
    const result = checkTlsMaterial(directory, { checkoutRoot: checkout, now: NOW });

    expect(result).toEqual({
      ok: false,
      problems: [
        `ca: ${join(directory, TLS_FILES.ca)} does not exist`,
        `leaf: ${join(directory, TLS_FILES.leaf)} does not exist`,
        `leafKey: ${join(directory, TLS_FILES.leafKey)} does not exist`,
      ],
    });
  });

  it('refuses a directory in the place of a file', () => {
    mkdirSync(join(directory, TLS_FILES.ca));
    write(TLS_FILES.leaf, '');
    write(TLS_FILES.leafKey, '');

    const result = checkTlsMaterial(directory, {
      checkoutRoot: checkout,
      now: NOW,
      platform: 'win32',
    });

    expect(result.ok).toBe(false);
    expect(!result.ok && result.problems[0]).toMatch(/^ca: .*ca\.pem is not a regular file$/);
  });

  // Break caught: a private key left readable by the other accounts of the machine.
  it('refuses a private key that others can read where the platform has modes, and notes that Windows has none to check', () => {
    write(TLS_FILES.ca, 'x');
    write(TLS_FILES.leaf, 'x');
    write(TLS_FILES.leafKey, 'x');

    // The mode of a file made on Windows is a synthetic 0666, which a platform with modes would refuse.
    const posix = checkTlsMaterial(directory, {
      checkoutRoot: checkout,
      now: NOW,
      platform: 'linux',
    });
    const windows = checkTlsMaterial(directory, {
      checkoutRoot: checkout,
      now: NOW,
      platform: 'win32',
    });

    expect(posix.ok).toBe(false);
    expect(
      !posix.ok && posix.problems.some((problem) => problem.includes('mode must be 0600')),
    ).toBe(true);
    expect(windows.ok).toBe(false);
    expect(!windows.ok && windows.problems).toEqual([
      'a certificate file could not be read as a certificate',
    ]);
  });

  it('refuses files that are not certificates', () => {
    write(TLS_FILES.ca, 'not a certificate');
    write(TLS_FILES.leaf, 'not a certificate');
    write(TLS_FILES.leafKey, 'not a key');

    expect(
      checkTlsMaterial(directory, { checkoutRoot: checkout, now: NOW, platform: 'win32' }),
    ).toEqual({
      ok: false,
      problems: ['a certificate file could not be read as a certificate'],
    });
  });

  // Break caught: a CA used as its own leaf, or a leaf that was signed by something else, accepted because each is a certificate.
  it('refuses a leaf that this CA did not sign, and says everything that is wrong at once', () => {
    write(TLS_FILES.ca, root.toString());
    write(TLS_FILES.leaf, otherRoot.toString());
    write(TLS_FILES.leafKey, 'not a key');

    const result = checkTlsMaterial(directory, {
      checkoutRoot: checkout,
      now: new Date(),
      platform: 'win32',
    });

    expect(result.ok).toBe(false);
    const problems = result.ok ? [] : result.problems;
    expect(problems).toContain('the leaf certificate does not name DNS:localhost');
    expect(problems).toContain('the leaf certificate was not signed by this CA');
    expect(problems).toContain('the private key file could not be read as a private key');
  });

  it('refuses a directory inside the checkout before it reads anything', () => {
    expect(checkTlsMaterial(join(checkout, 'tls'), { checkoutRoot: checkout, now: NOW })).toEqual({
      ok: false,
      problems: [
        'the TLS directory is inside the repository checkout: test key material is kept outside it',
      ],
    });
  });
});

