/**
 * The policy for the test certificates of the trusted HTTPS origin (S0.23). **No certificate is generated by any test here and no
 * private key exists in this file**: the facts are judged on invented facts and on the public root certificates that Node itself
 * carries, which are real certificates nobody here signed. What needs a CA this checkout has not made (a leaf that this CA signed,
 * a private key that is that leaf's, the accepting path of `checkTlsMaterial`) is exercised by the run on a clean machine or in CI
 * (`e2e/README.md`), and is reported blocked until then.
 */
const NOW = new Date('2026-10-11T12:00:00Z');
const DAY = 86_400_000;

const acceptableCa: CertificateFacts = {
  subject: 'CN=Melarc test CA',
  issuer: 'CN=Melarc test CA',
  isCa: true,
  validFrom: new Date(NOW.getTime() - DAY),
  validTo: new Date(NOW.getTime() + 7 * DAY),
  alternativeNames: [],
  nameConstraints: 'critical',
  selfSignatureValid: true,
  fingerprint256: 'AA:BB',
};
const acceptableLeaf: CertificateFacts = {
  subject: 'CN=localhost',
  issuer: 'CN=Melarc test CA',
  isCa: false,
  validFrom: new Date(NOW.getTime() - DAY),
  validTo: new Date(NOW.getTime() + 7 * DAY),
  alternativeNames: ['DNS:localhost', 'IP Address:127.0.0.1'],
  nameConstraints: 'absent',
  selfSignatureValid: false,
  fingerprint256: 'CC:DD',
};

/** Public roots that are valid today and for years: real certificates, with the properties of one (a CA, self-signed). */
const [root, otherRoot] = ((): [X509Certificate, X509Certificate] => {
  const valid = rootCertificates
    .map((pem) => new X509Certificate(pem))
    .filter(
      (candidate) =>
        new Date(candidate.validFrom).getTime() < Date.now() &&
        new Date(candidate.validTo).getTime() > Date.now() + 365 * DAY,
    );
  const [first, second] = valid;
  if (first === undefined || second === undefined) {
    throw new Error('Node carries fewer than two root certificates that are valid today');
  }
  return [first, second];
})();

describe('what is read from a certificate', () => {
  // Break caught: the facts read from the wrong fields (the issuer for the subject, the end for the start), so that a policy
  // judged on them passes what it should not.
  it('reads the role, the names and the validity of a real root certificate', () => {
    const facts = factsOf(root);

    expect(facts.isCa).toBe(true);
    expect(facts.subject).toBe(facts.issuer);
    expect(facts.validFrom.getTime()).toBeLessThan(facts.validTo.getTime());
    expect(facts.alternativeNames).toEqual([]);
    expect(facts.nameConstraints).toBe('absent');
    // A real root verifies under its own key, and a certificate that another key signed does not.
    expect(facts.selfSignatureValid).toBe(true);
    expect(otherRoot.verify(root.publicKey)).toBe(false);
    expect(facts.fingerprint256).toMatch(/^([0-9A-F]{2}:){31}[0-9A-F]{2}$/);
  });
});

// Break caught: the signature checked against some other key, or not checked: the fact must follow what the certificate's own key
// says of its own signature. Every real root verifies, so a stand-in whose `verify` answers by the key it is given is what shows it.
describe('the self-signature as a fact', () => {
  const standIn = (verify: (key: unknown) => boolean): X509Certificate =>
    ({
      subject: 'CN=x',
      issuer: 'CN=x',
      ca: true,
      validFrom: 'Oct 1 00:00:00 2026 GMT',
      validTo: 'Oct 8 00:00:00 2026 GMT',
      subjectAltName: undefined,
      raw: Buffer.alloc(0),
      fingerprint256: 'AA',
      publicKey: 'its-own-key',
      verify,
    }) as unknown as X509Certificate;

  it('is true when the certificate verifies under its own public key, and false when only another key would do', () => {
    expect(factsOf(standIn((key) => key === 'its-own-key')).selfSignatureValid).toBe(true);
    expect(factsOf(standIn((key) => key === 'another-key')).selfSignatureValid).toBe(false);
  });
});

/** DER by hand: a tag, a length (short or long form) and content. There is no key and no signature in any of it. */
const der = (tag: number, ...content: (Buffer | number[])[]): Buffer => {
  const body = Buffer.concat(content.map((part) => Buffer.from(part)));
  const length =
    body.length < 0x80
      ? [body.length]
      : body.length < 0x100
        ? [0x81, body.length]
        : [0x82, body.length >> 8, body.length & 0xff];
  return Buffer.concat([Buffer.from([tag, ...length]), body]);
};
const oid = (...octets: number[]): Buffer => der(0x06, octets);
const BASIC_CONSTRAINTS = oid(0x55, 0x1d, 0x13);
const NAME_CONSTRAINTS = oid(0x55, 0x1d, 0x1e);
const extension = (identifier: Buffer, critical: boolean, value: Buffer): Buffer =>
  der(0x30, identifier, ...(critical ? [der(0x01, [0xff])] : []), der(0x04, value));
/** A certificate-shaped value: the nesting the reader walks, with the extensions given. */
const certificateWith = (...extensions: Buffer[]): Buffer =>
  der(
    0x30,
    der(
      0x30,
      der(0xa0, der(0x02, [2])),
      der(0x02, [1]),
      der(0x30, oid(0x2a, 0x86, 0x48, 0xce, 0x3d, 0x04, 0x03, 0x02)),
      der(0x30),
      der(0x30),
      der(0x30),
      der(0x30),
      der(0xa3, der(0x30, ...extensions)),
    ),
    der(0x30, oid(0x2a, 0x86, 0x48, 0xce, 0x3d, 0x04, 0x03, 0x02)),
    der(0x03, [0, 1, 2, 3]),
  );
/** The value of a name constraints extension for the loopback, as `openssl` writes it. Its content is not read. */
const LOOPBACK_CONSTRAINTS = der(
  0x30,
  der(
    0xa0,
    der(0x30, der(0x82, Buffer.from('localhost'))),
    der(0x30, der(0x87, [127, 0, 0, 1, 255, 255, 255, 255])),
  ),
);

describe('the extensions read from a certificate', () => {
  // Break caught: a reader that works on the shapes written here and not on certificates: every root Node carries is a real
  // certificate whose basicConstraints and key usage must be found, and the identifiers decoded to the numbers they are known by.
  it('finds the extensions of every real root certificate, as Node reads the same certificate', () => {
    let read = 0;
    for (const pem of rootCertificates) {
      const certificate = new X509Certificate(pem);
      const found = extensionsOf(certificate.raw);
      read += 1;
      expect(found.length, certificate.subject).toBeGreaterThan(0);
      if (certificate.ca) {
        expect(
          found.some((entry) => entry.id === '2.5.29.19'),
          certificate.subject,
        ).toBe(true);
      }
      expect(nameConstraintsOf(certificate.raw), certificate.subject).toBe('absent');
    }
    expect(read).toBeGreaterThan(0);
  });

  it('decodes an identifier with arcs above 127 and a first arc of 1 or 2', () => {
    const identifiers = certificateWith(
      extension(oid(0x2b, 0x06, 0x01, 0x04, 0x01, 0x82, 0x37, 0x15, 0x01), false, Buffer.from([5])),
      extension(oid(0x55, 0x1d, 0x13), true, Buffer.from([5])),
      extension(oid(0x88, 0x37, 0x03), false, Buffer.from([5])),
    );

    expect(extensionsOf(identifiers)).toEqual([
      { id: '1.3.6.1.4.1.311.21.1', critical: false },
      { id: '2.5.29.19', critical: true },
      { id: '2.999.3', critical: false },
    ]);
  });

  // Break caught: the presence read from the bytes alone, so that the same five octets in another place counts as the extension.
  it('finds the name constraints, critical or not, and nothing where they are not', () => {
    const critical = certificateWith(
      extension(BASIC_CONSTRAINTS, true, Buffer.from([0x30, 0x00])),
      extension(NAME_CONSTRAINTS, true, LOOPBACK_CONSTRAINTS),
    );
    const notCritical = certificateWith(extension(NAME_CONSTRAINTS, false, LOOPBACK_CONSTRAINTS));
    const absent = certificateWith(extension(BASIC_CONSTRAINTS, true, Buffer.from([0x30, 0x00])));
    const lookalike = certificateWith(
      extension(oid(0x55, 0x1d, 0x1f), true, LOOPBACK_CONSTRAINTS),
      extension(oid(0x55, 0x1d, 0x1e, 0x01), true, LOOPBACK_CONSTRAINTS),
      extension(BASIC_CONSTRAINTS, true, NAME_CONSTRAINTS),
    );

    expect(nameConstraintsOf(critical)).toBe('critical');
    expect(nameConstraintsOf(notCritical)).toBe('not-critical');
    expect(nameConstraintsOf(absent)).toBe('absent');
    expect(nameConstraintsOf(certificateWith())).toBe('absent');
    expect(nameConstraintsOf(lookalike)).toBe('absent');
  });

  // Break caught: a length in the long form mis-read, so that an extension after a large one (a key usage list, a policy) is lost.
  it('reads past an extension whose length is written in the long form', () => {
    const large = Buffer.alloc(300, 0x61);
    const certificate = certificateWith(
      extension(oid(0x55, 0x1d, 0x20), false, large),
      extension(NAME_CONSTRAINTS, true, LOOPBACK_CONSTRAINTS),
    );

    expect(nameConstraintsOf(certificate)).toBe('critical');
  });

  // Break caught: a reader that throws on, loops on or trusts input that is not a certificate: it must find nothing and say nothing.
  it('finds nothing in what is not a certificate, however it is cut or written', () => {
    const whole = certificateWith(extension(NAME_CONSTRAINTS, true, LOOPBACK_CONSTRAINTS));
    const cuts = [0, 1, 2, 10, 40, whole.length - 5, whole.length - 1];

    expect(nameConstraintsOf(whole)).toBe('critical');
    for (const cut of cuts) {
      expect(nameConstraintsOf(whole.subarray(0, cut)), `cut at ${String(cut)}`).toBe('absent');
    }
    expect(nameConstraintsOf(Buffer.alloc(0))).toBe('absent');
    expect(nameConstraintsOf(Buffer.from('not a certificate'))).toBe('absent');
    expect(nameConstraintsOf(Buffer.from([0x30, 0x80, 0x00, 0x00]))).toBe('absent');
    expect(nameConstraintsOf(Buffer.from([0x30, 0x84, 0xff, 0xff, 0xff, 0xff]))).toBe('absent');
    expect(nameConstraintsOf(Buffer.from([0x1f, 0x81, 0x01, 0x00]))).toBe('absent');
  });

  // Break caught: an element with a tag the reader does not understand skipped as if it had been read, and what follows it believed.
  it('stops at an element it cannot read and does not go on to believe what follows', () => {
    const certificate = certificateWith(
      Buffer.from([0x1f, 0x01, 0x00]),
      extension(NAME_CONSTRAINTS, true, LOOPBACK_CONSTRAINTS),
    );

    expect(extensionsOf(certificate)).toEqual([]);
    expect(nameConstraintsOf(certificate)).toBe('absent');
  });
});

describe('the certificate policy', () => {
  it('accepts a short-lived CA and a short-lived leaf that names the loopback', () => {
    expect(certificateProblems('ca', acceptableCa, NOW)).toEqual([]);
    expect(certificateProblems('leaf', acceptableLeaf, NOW)).toEqual([]);
  });

  // Break caught: a long-lived CA kept as test material: if its key were ever taken, what trusts it would trust it for years.
  it('refuses a certificate valid for more than a month, a real root among them', () => {
    expect(certificateProblems('ca', factsOf(root), new Date())).toEqual([
      `the CA certificate is valid for more than ${String(MAX_VALID_DAYS)} days: test material is disposable`,
      'the CA certificate has no name constraints: it could vouch for any name',
    ]);
    const long = { ...acceptableLeaf, validTo: new Date(NOW.getTime() + 40 * DAY) };

    expect(certificateProblems('leaf', long, NOW)).toEqual([
      `the leaf certificate is valid for more than ${String(MAX_VALID_DAYS)} days: test material is disposable`,
    ]);
  });

  it('accepts a validity of exactly the limit and refuses one second over', () => {
    const exact = {
      ...acceptableLeaf,
      validTo: new Date(acceptableLeaf.validFrom.getTime() + MAX_VALID_DAYS * DAY),
    };
    const over = { ...exact, validTo: new Date(exact.validTo.getTime() + 1) };

    expect(certificateProblems('leaf', exact, NOW)).toEqual([]);
    expect(certificateProblems('leaf', over, NOW)).toHaveLength(1);
  });

  // Break caught: an expired or not-yet-valid certificate taken, so that the first failure of a run is a handshake.
  it('refuses a certificate that is not valid now', () => {
    const early = {
      ...acceptableCa,
      validFrom: new Date(NOW.getTime() + DAY),
      validTo: new Date(NOW.getTime() + 2 * DAY),
    };
    const late = {
      ...acceptableCa,
      validFrom: new Date(NOW.getTime() - 3 * DAY),
      validTo: new Date(NOW.getTime() - DAY),
    };
    const justEnded = { ...acceptableCa, validTo: NOW };

    expect(certificateProblems('ca', early, NOW)).toEqual(['the CA certificate is not valid yet']);
    expect(certificateProblems('ca', late, NOW)).toEqual(['the CA certificate has expired']);
    expect(certificateProblems('ca', justEnded, NOW)).toEqual(['the CA certificate has expired']);
  });

  // Break caught: a leaf that is itself a CA (which could mint certificates for anything), or a CA that is not one, or not self-signed.
  it('holds the CA to being a self-signed authority and the leaf to not being one', () => {
    expect(certificateProblems('ca', { ...acceptableCa, isCa: false }, NOW)).toEqual([
      'the CA certificate is not a certificate authority',
    ]);
    expect(certificateProblems('ca', { ...acceptableCa, issuer: 'CN=Someone else' }, NOW)).toEqual([
      'the CA certificate is not self-signed',
    ]);
    expect(certificateProblems('leaf', { ...acceptableLeaf, isCa: true }, NOW)).toEqual([
      'the leaf certificate is a certificate authority',
    ]);
  });

  // Break caught: a CA that can vouch for any name accepted as the disposable one: whatever came to trust it would be exposed to a
  // certificate for every site, and the constraints are what stops a leaked key from being that.
  it('requires the CA to carry name constraints and to mark them critical', () => {
    expect(certificateProblems('ca', { ...acceptableCa, nameConstraints: 'absent' }, NOW)).toEqual([
      'the CA certificate has no name constraints: it could vouch for any name',
    ]);
    expect(
      certificateProblems('ca', { ...acceptableCa, nameConstraints: 'not-critical' }, NOW),
    ).toEqual([
      'the name constraints of the CA certificate are not critical: a client that does not understand them would ignore them',
    ]);
  });

  // Break caught: a certificate that says it is self-signed (subject equal to issuer) and was signed by another key, or by none.
  it('requires the CA to verify under its own key, not only to say that it is self-signed', () => {
    expect(certificateProblems('ca', { ...acceptableCa, selfSignatureValid: false }, NOW)).toEqual([
      'the CA certificate is not signed by its own key',
    ]);
    // Not reported twice: a certificate that is not even self-signed by name has one problem.
    expect(
      certificateProblems(
        'ca',
        { ...acceptableCa, issuer: 'CN=Someone else', selfSignatureValid: false },
        NOW,
      ),
    ).toEqual(['the CA certificate is not self-signed']);
  });

  // Break caught: a leaf that names the loopback and more, which a browser would accept for the other names as well.
  it('refuses a leaf that names anything beyond the loopback', () => {
    const extra = {
      ...acceptableLeaf,
      alternativeNames: [
        ...acceptableLeaf.alternativeNames,
        'DNS:example.com',
        'IP Address:10.0.0.1',
      ],
    };

    expect(certificateProblems('leaf', extra, NOW)).toEqual([
      'the leaf certificate names DNS:example.com, which is outside the loopback',
      'the leaf certificate names IP Address:10.0.0.1, which is outside the loopback',
    ]);
    expect(
      certificateProblems('leaf', { ...acceptableLeaf, alternativeNames: ['DNS:*'] }, NOW),
    ).toContain('the leaf certificate names DNS:*, which is outside the loopback');
  });

  // Break caught: a leaf that does not name the host the browser opens, which a browser refuses, for a reason found only in it.
  it('requires the leaf to name localhost and 127.0.0.1', () => {
    expect(
      certificateProblems('leaf', { ...acceptableLeaf, alternativeNames: ['DNS:localhost'] }, NOW),
    ).toEqual(['the leaf certificate does not name IP Address:127.0.0.1']);
    expect(
      certificateProblems('leaf', { ...acceptableLeaf, alternativeNames: [] }, NOW),
    ).toHaveLength(2);
  });
});

