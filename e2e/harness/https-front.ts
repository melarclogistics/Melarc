import { readFileSync } from 'node:fs';
import {
  createServer as createHttpServer,
  request as httpRequest,
  type IncomingHttpHeaders,
  type IncomingMessage,
  type ServerResponse,
} from 'node:http';
import { createServer as createHttpsServer } from 'node:https';
import type { AddressInfo } from 'node:net';

import type { TlsMaterial } from './tls-material.ts';

/**
 * The browser-facing edge of the harness (S0.23; implementation plan §11.5): a TLS-terminating reverse proxy in front of the Ops
 * origin, so that a browser reaches the product the way it will in production, over HTTPS with a certificate it really validates
 * (the cookies of the identity slice are `Secure`, which a plain-HTTP origin cannot prove in every engine). It is the stand-in for
 * the edge, and it does what the edge is required to do for a browser surface and the application does not
 * (DEPLOYMENT_AND_ENVIRONMENTS.md §12.2; security matrix `GBT-W9`): it adds the response headers, and it forwards everything else
 * unchanged, `Set-Cookie` included, to the Ops preview server, which proxies `/api/v1` to the API (the same-origin arrangement).
 *
 * What it is not. It is not part of the product and nothing outside the harness runs it. The values of its headers are the
 * harness's own and are not the production edge's, which are release gate G2 (HSTS in particular is "once the domain and
 * certificates are validated"). It never serves an application route of its own, adds no cookie, reads no body, and terminates TLS
 * with the disposable leaf of `tls-material.ts`: the leaf's private key is read from disk into the server, and nothing here prints it.
 *
 * Without TLS material it serves plain HTTP. That form exists for the unit tests of the proxying and the headers, which have no
 * certificate (none is ever generated by a test), and **the stack never starts it**: the stack starts the front with material, or
 * not at all.
 */

/**
 * The policy of the shell's compatibility baseline (`apps/ops-web/test/browser/shell.spec.ts`, `STRICT_POLICY`): nothing inline,
 * no eval, nothing from another origin, no framing. The shell is held to work under it, so the front can send it for real.
 */
export const CONTENT_SECURITY_POLICY = [
  "default-src 'none'",
  "script-src 'self'",
  "style-src 'self'",
  "img-src 'self'",
  "font-src 'self'",
  "connect-src 'self'",
  "base-uri 'none'",
  "form-action 'self'",
  "frame-ancestors 'none'",
].join('; ');

/** The headers the front sets on every response, replacing any the upstream sent under the same name. */
export const EDGE_HEADERS: Readonly<Record<string, string>> = Object.freeze({
  'content-security-policy': CONTENT_SECURITY_POLICY,
  'x-content-type-options': 'nosniff',
  'referrer-policy': 'no-referrer',
  'strict-transport-security': 'max-age=31536000',
});

/** Headers that describe a single connection and are not forwarded in either direction (RFC 9110 section 7.6.1). */
const HOP_BY_HOP = new Set([
  'connection',
  'keep-alive',
  'proxy-authenticate',
  'proxy-authorization',
  'te',
  'trailer',
  'transfer-encoding',
  'upgrade',
]);

export interface HttpsFrontOptions {
  /** The Ops origin's address, `http://127.0.0.1:<port>`: where every request is forwarded. */
  readonly upstream: string;
  /** The leaf and its key. Absent: plain HTTP, for the unit tests only. */
  readonly tls?: Pick<TlsMaterial, 'leafPath' | 'leafKeyPath'>;
  /** Defaults to the loopback address; the port is chosen by the system when it is 0. */
  readonly host?: string;
  readonly port?: number;
  /** The TLS server factory. Only the unit tests replace it, to see what it is given without a certificate. */
  readonly tlsServer?: TlsServerFactory;
}

export interface TlsServerOptions {
  readonly key: Buffer;
  readonly cert: Buffer;
  readonly minVersion: 'TLSv1.2';
}
/** What the front needs of a server: both `http.Server` and `https.Server` have it. */
export interface Listener {
  listen(port: number, host: string, callback: () => void): unknown;
  address(): AddressInfo | string | null;
  closeAllConnections(): void;
  close(callback: () => void): unknown;
  once(event: 'error', handler: (error: Error) => void): unknown;
  off(event: 'error', handler: (error: Error) => void): unknown;
}
export type TlsServerFactory = (
  options: TlsServerOptions,
  handler: (request: IncomingMessage, response: ServerResponse) => void,
) => Listener;

export interface HttpsFront {
  /** The origin a browser opens, with the host name the leaf names: `https://localhost:<port>`. */
  readonly origin: string;
  readonly port: number;
  stop(): Promise<void>;
}

function forwardedHeaders(headers: IncomingHttpHeaders): IncomingHttpHeaders {
  const kept: IncomingHttpHeaders = {};
  for (const [name, value] of Object.entries(headers)) {
    if (!HOP_BY_HOP.has(name.toLowerCase())) kept[name] = value;
  }
  return kept;
}

function proxy(upstream: URL, request: IncomingMessage, response: ServerResponse): void {
  const outgoing = httpRequest(
    {
      protocol: upstream.protocol,
      hostname: upstream.hostname,
      port: upstream.port,
      method: request.method,
      path: request.url,
      headers: forwardedHeaders(request.headers),
    },
    (incoming) => {
      // The edge's own headers replace whatever the upstream sent under those names, in any case.
      const headers = Object.fromEntries(
        Object.entries(forwardedHeaders(incoming.headers)).filter(
          ([name]) => !(name.toLowerCase() in EDGE_HEADERS),
        ),
      );
      response.writeHead(incoming.statusCode ?? 502, incoming.statusMessage, {
        ...headers,
        ...EDGE_HEADERS,
      });
      incoming.pipe(response);
    },
  );
  outgoing.on('error', () => {
    if (!response.headersSent) response.writeHead(502, { ...EDGE_HEADERS });
    response.end();
  });
  request.pipe(outgoing);
}

/** Starts the front and resolves when it listens. */
export async function startHttpsFront(options: HttpsFrontOptions): Promise<HttpsFront> {
  const upstream = new URL(options.upstream);
  if (upstream.protocol !== 'http:') {
    throw new TypeError('The front forwards to the Ops origin over plain HTTP on this machine.');
  }
  const handler = (request: IncomingMessage, response: ServerResponse): void => {
    proxy(upstream, request, response);
  };
  const server: Listener =
    options.tls === undefined
      ? createHttpServer(handler)
      : (options.tlsServer ?? createHttpsServer)(
          {
            key: readFileSync(options.tls.leafKeyPath),
            cert: readFileSync(options.tls.leafPath),
            // TLS 1.2 is the floor (DEPLOYMENT_AND_ENVIRONMENTS.md §12.2: 1.3 preferred, 1.2 for compatibility, nothing older).
            minVersion: 'TLSv1.2',
          },
          handler,
        );

  await new Promise<void>((resolve, reject) => {
    server.once('error', reject);
    server.listen(options.port ?? 0, options.host ?? '127.0.0.1', () => {
      server.off('error', reject);
      resolve();
    });
  });
  const { port } = server.address() as AddressInfo;
  const scheme = options.tls === undefined ? 'http' : 'https';
  return {
    // The host name the leaf names, not the address the server listens on: a name the certificate does not cover is a name the
    // browser would refuse, and the cookies are host-only, so the origin the API is configured with is this one exactly.
    origin: `${scheme}://localhost:${String(port)}`,
    port,
    stop: () =>
      new Promise<void>((resolve) => {
        server.closeAllConnections();
        server.close(() => {
          resolve();
        });
      }),
  };
}
