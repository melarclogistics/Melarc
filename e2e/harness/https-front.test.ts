import { mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import {
  createServer,
  request as httpRequest,
  type IncomingHttpHeaders,
  type Server,
} from 'node:http';
import type { AddressInfo } from 'node:net';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

import { afterEach, beforeEach, describe, expect, it } from 'vitest';

import {
  CONTENT_SECURITY_POLICY,
  EDGE_HEADERS,
  startHttpsFront,
  type HttpsFront,
  type TlsServerOptions,
} from './https-front.ts';

/**
 * The front of the trusted HTTPS origin (S0.23), proved on what has no need of a certificate: what it adds to a response, what it
 * forwards in each direction, and what it does when the upstream is not there. **No certificate or key is generated by any test
 * here**; the TLS branch is seen through a factory that records what it is given. That a browser validates the leaf is proved by the
 * run in the clean environment (`e2e/README.md`).
 */
interface Seen {
  readonly method: string | undefined;
  readonly url: string | undefined;
  readonly headers: IncomingHttpHeaders;
  readonly body: string;
}

let upstream: Server;
let upstreamPort = 0;
let seen: Seen[] = [];
let reply: (url: string) => {
  status: number;
  headers: Record<string, string | string[]>;
  body: string;
} = () => ({
  status: 200,
  headers: {},
  body: 'ok',
});
const fronts: HttpsFront[] = [];
let directory = '';

beforeEach(async () => {
  seen = [];
  reply = () => ({ status: 200, headers: {}, body: 'ok' });
  directory = mkdtempSync(join(tmpdir(), 'melarc-front-'));
  upstream = createServer((request, response) => {
    const chunks: Buffer[] = [];
    request.on('data', (chunk: Buffer) => chunks.push(chunk));
    request.on('end', () => {
      seen.push({
        method: request.method,
        url: request.url,
        headers: request.headers,
        body: Buffer.concat(chunks).toString('utf8'),
      });
      const answer = reply(request.url ?? '');
      response.writeHead(answer.status, answer.headers);
      response.end(answer.body);
    });
  });
  await new Promise<void>((resolve) => upstream.listen(0, '127.0.0.1', resolve));
  upstreamPort = (upstream.address() as AddressInfo).port;
});

afterEach(async () => {
  for (const front of fronts.splice(0)) await front.stop();
  upstream.closeAllConnections();
  await new Promise<void>((resolve) =>
    upstream.close(() => {
      resolve();
    }),
  );
  rmSync(directory, { recursive: true, force: true });
});

async function front(options: Partial<Parameters<typeof startHttpsFront>[0]> = {}) {
  const started = await startHttpsFront({
    upstream: `http://127.0.0.1:${String(upstreamPort)}`,
    ...options,
  });
  fronts.push(started);
  return started;
}
const get = (started: HttpsFront, path: string, init: RequestInit = {}) =>
  fetch(`http://127.0.0.1:${String(started.port)}${path}`, { redirect: 'manual', ...init });

describe('what the front adds to a response (GBT-W9)', () => {
  // Break caught: a browser surface response without the edge headers, on any status: the page, a missing asset, an upstream failure.
  it.each([200, 404, 500])('sets the edge headers on a %s from the upstream', async (status) => {
    reply = () => ({ status, headers: {}, body: 'x' });
    const started = await front();

    const response = await get(started, '/anything');

    expect(response.status).toBe(status);
    for (const [name, value] of Object.entries(EDGE_HEADERS)) {
      expect(response.headers.get(name), name).toBe(value);
    }
  });

  // Break caught: the policy of the front drifting from the baseline the shell is tested under, or becoming one that allows the
  // page to be framed, to run inline code or to reach another origin.
  it('sends a policy with no inline code, no eval, no other origin and no framing', () => {
    expect(EDGE_HEADERS['content-security-policy']).toBe(CONTENT_SECURITY_POLICY);
    const directives = CONTENT_SECURITY_POLICY.split('; ');
    expect(directives).toContain("default-src 'none'");
    expect(directives).toContain("frame-ancestors 'none'");
    expect(directives).toContain("script-src 'self'");
    expect(CONTENT_SECURITY_POLICY).not.toMatch(/unsafe-inline|unsafe-eval|\*|https?:/);
    expect(EDGE_HEADERS['x-content-type-options']).toBe('nosniff');
    expect(EDGE_HEADERS['referrer-policy']).toBe('no-referrer');
    expect(EDGE_HEADERS['strict-transport-security']).toMatch(/^max-age=\d+$/);
  });

  // Break caught: an upstream that weakens the edge's headers (a wider policy, sniffing allowed) winning over the front's.
  it('replaces a header the upstream sent under the same name', async () => {
    reply = () => ({
      status: 200,
      headers: {
        'Content-Security-Policy': 'default-src *',
        'X-Content-Type-Options': 'sniff',
        'Referrer-Policy': 'unsafe-url',
      },
      body: 'x',
    });
    const started = await front();

    const response = await get(started, '/');

    expect(response.headers.get('content-security-policy')).toBe(CONTENT_SECURITY_POLICY);
    expect(response.headers.get('x-content-type-options')).toBe('nosniff');
    expect(response.headers.get('referrer-policy')).toBe('no-referrer');
  });
});

describe('what the front forwards', () => {
  // Break caught: a cookie rewritten, merged or dropped on its way to the browser: the attributes (Secure, HttpOnly, SameSite, Path,
  // no Domain) are the application's and the front must not touch them; two cookies stay two header lines.
  it('forwards every Set-Cookie line unchanged, one by one', async () => {
    const cookies = [
      'melarc_session=abc; Path=/; Secure; HttpOnly; SameSite=Strict',
      'melarc_csrf=def; Path=/; Secure; SameSite=Strict',
    ];
    reply = () => ({ status: 200, headers: { 'Set-Cookie': cookies }, body: 'x' });
    const started = await front();

    const response = await get(started, '/');

    expect(response.headers.getSetCookie()).toEqual(cookies);
  });

  // Break caught: a request changed on its way to the application: the method, the path and query, the credential, the Origin the
  // API judges, the CSRF token or the body.
  it('forwards the method, the path, the headers and the body of a request unchanged', async () => {
    const started = await front();

    await get(started, '/api/v1/things?x=1&y=%20', {
      method: 'POST',
      headers: {
        cookie: 'melarc_session=abc; melarc_csrf=def',
        origin: started.origin,
        'x-csrf-token': 'def',
        'content-type': 'application/json',
        authorization: 'Bearer token-value',
      },
      body: '{"a":1}',
    });

    expect(seen).toHaveLength(1);
    expect(seen[0]).toMatchObject({
      method: 'POST',
      url: '/api/v1/things?x=1&y=%20',
      body: '{"a":1}',
    });
    expect(seen[0]?.headers).toMatchObject({
      cookie: 'melarc_session=abc; melarc_csrf=def',
      origin: started.origin,
      'x-csrf-token': 'def',
      'content-type': 'application/json',
      authorization: 'Bearer token-value',
    });
  });

  it('forwards the status and the body of the response', async () => {
    reply = () => ({
      status: 403,
      headers: { 'Content-Type': 'application/json' },
      body: '{"code":"X"}',
    });
    const started = await front();

    const response = await get(started, '/api/v1/x');

    expect(response.status).toBe(403);
    expect(response.headers.get('content-type')).toBe('application/json');
    expect(await response.text()).toBe('{"code":"X"}');
  });

  // Break caught: a header that belongs to one connection passed on to the next, which would confuse the upstream's framing.
  it('does not forward the headers of the connection itself', async () => {
    const started = await front();

    // `fetch` refuses to send these, so the request is made with the lower-level client.
    await new Promise<void>((resolve, reject) => {
      const outgoing = httpRequest(
        {
          host: '127.0.0.1',
          port: started.port,
          path: '/',
          headers: {
            connection: 'keep-alive',
            'keep-alive': 'timeout=5',
            te: 'trailers',
            'x-kept': 'yes',
          },
        },
        (response) => {
          response.resume();
          response.on('end', resolve);
        },
      );
      outgoing.on('error', reject);
      outgoing.end();
    });

    expect(seen[0]?.headers['keep-alive']).toBeUndefined();
    expect(seen[0]?.headers.te).toBeUndefined();
    expect(seen[0]?.headers['x-kept']).toBe('yes');
  });

  // Break caught: an upstream failure answered with a hang, a reset or a body that leaks where the upstream is.
  it('answers 502 with the edge headers, and no body, when the upstream is not there', async () => {
    const started = await front({ upstream: 'http://127.0.0.1:1' });

    const response = await get(started, '/');

    expect(response.status).toBe(502);
    expect(await response.text()).toBe('');
    expect(response.headers.get('content-security-policy')).toBe(CONTENT_SECURITY_POLICY);
  });
});

describe('the origin it is opened at, and the TLS it is given', () => {
  // Break caught: an origin spelled with the address it listens on, which the leaf does not name as a host the browser would use,
  // and which the API (configured with this exact origin) would judge a different origin from the page's.
  it('is opened at the host name the leaf names, with the scheme it serves', async () => {
    const plain = await front();
    expect(plain.origin).toBe(`http://localhost:${String(plain.port)}`);
  });

  // Break caught: the key or certificate read from somewhere else, a TLS floor lower than 1.2, or TLS silently not used.
  it('gives the TLS server the leaf and its key, a floor of TLS 1.2, and serves https', async () => {
    writeFileSync(join(directory, 'leaf.pem'), 'CERTIFICATE-TEXT');
    writeFileSync(join(directory, 'leaf-key.pem'), 'KEY-TEXT');
    let given: TlsServerOptions | undefined;

    const started = await front({
      tls: { leafPath: join(directory, 'leaf.pem'), leafKeyPath: join(directory, 'leaf-key.pem') },
      tlsServer: (options, handler) => {
        given = options;
        return createServer(handler);
      },
    });

    expect(given?.cert.toString('utf8')).toBe('CERTIFICATE-TEXT');
    expect(given?.key.toString('utf8')).toBe('KEY-TEXT');
    expect(given?.minVersion).toBe('TLSv1.2');
    expect(started.origin).toBe(`https://localhost:${String(started.port)}`);
  });

  it('refuses an upstream that is not plain HTTP on this machine', async () => {
    await expect(startHttpsFront({ upstream: 'https://example.com' })).rejects.toBeInstanceOf(
      TypeError,
    );
  });

  it('stops: nothing answers afterwards', async () => {
    const started = await front();
    await started.stop();
    fronts.splice(fronts.indexOf(started), 1);

    await expect(get(started, '/')).rejects.toThrow();
  });
});
